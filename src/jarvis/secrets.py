"""Secret storage backed by the system credential store (``keyring``).

API keys, the IPC token, and the Argon2id password hash live in the Windows
Credential Manager (service name ``jarvis``) and are never written to files,
logs, LLM prompts, or checkpoints. Values are never logged by this module.
"""

from __future__ import annotations

import logging

import keyring

logger = logging.getLogger(__name__)

SECRET_SERVICE_NAME = "jarvis"

